import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const { GLOBE_DOT_COUNT }: typeof import('../src/lib/globe/look') = await import(
  new URL('../src/lib/globe/look.ts', import.meta.url).href
);
const { getFibonacciPoints, getPointLatLon }: typeof import('../src/lib/globe/sphere') =
  await import(new URL('../src/lib/globe/sphere.ts', import.meta.url).href);

type Ring = [number, number][];
type Geometry =
  | { type: 'Polygon'; coordinates: Ring[] }
  | { type: 'MultiPolygon'; coordinates: Ring[][] };

const OUTPUT_PATH = path.resolve(import.meta.dirname, '../src/lib/globe/land-mask.data.ts');
const SOURCE_URL =
  'https://raw.githubusercontent.com/nvkelso/natural-earth-vector/v5.1.2/geojson/ne_110m_land.geojson';

function getRings(geometry: Geometry): Ring[] {
  return geometry.type === 'Polygon' ? geometry.coordinates : geometry.coordinates.flat();
}

function isInsideRing(ring: Ring, lon: number, lat: number): boolean {
  let inside = false;
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [xi, yi] = ring[i];
    const [xj, yj] = ring[j];
    if (yi > lat !== yj > lat && lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) inside = !inside;
  }
  return inside;
}

const inputPath = process.argv[2];
if (!inputPath)
  throw new Error(
    `Usage: node scripts/build-globe-land.ts <ne_110m_land.geojson from ${SOURCE_URL}>`,
  );

const { features } = JSON.parse(readFileSync(inputPath, 'utf8')) as {
  features: { geometry: Geometry }[];
};
const rings = features.flatMap(({ geometry }) => getRings(geometry));
const points = getFibonacciPoints(GLOBE_DOT_COUNT);
const bits = new Uint8Array(Math.ceil(GLOBE_DOT_COUNT / 8));
let landCount = 0;

for (let i = 0; i < GLOBE_DOT_COUNT; i++) {
  const { lat, lon } = getPointLatLon(points[i * 3], points[i * 3 + 1], points[i * 3 + 2]);
  const crossings = rings.filter((ring) => isInsideRing(ring, lon, lat)).length;
  if (crossings % 2 === 1) {
    bits[i >> 3] |= 1 << (i & 7);
    landCount++;
  }
}

const base64 = Buffer.from(bits).toString('base64');
writeFileSync(
  OUTPUT_PATH,
  `// Generated by scripts/build-globe-land.ts from Natural Earth 1:110m land (public domain): ${SOURCE_URL}\n` +
    `export const LAND_MASK_POINT_COUNT = ${GLOBE_DOT_COUNT};\n` +
    `export const LAND_MASK_BASE64 =\n  '${base64}';\n`,
);
console.log(`Wrote ${landCount}/${GLOBE_DOT_COUNT} land points to ${OUTPUT_PATH}`);

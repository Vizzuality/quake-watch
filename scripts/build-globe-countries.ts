import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

type CountryProperties = {
  LABELRANK: number;
  MIN_LABEL: number;
  LABEL_X: number;
  LABEL_Y: number;
  NAME?: string;
  NAME_ES?: string;
  NAME_PT?: string;
};

type CountryLabel = {
  lat: number;
  lon: number;
  rank: number;
  name: { en: string; es: string; pt: string };
};

const OUTPUT_PATH = path.resolve(import.meta.dirname, '../src/lib/globe/country-labels.data.ts');
const SOURCE_URL =
  'https://raw.githubusercontent.com/nvkelso/natural-earth-vector/v5.1.2/geojson/ne_50m_admin_0_countries.geojson';
const MAX_LABEL_RANK = 7;

const [inputPath] = process.argv.slice(2);
if (!inputPath)
  throw new Error(
    `Usage: node scripts/build-globe-countries.ts <ne_50m_admin_0_countries.geojson from ${SOURCE_URL}>`,
  );

function getRounded(value: number): number {
  return Math.round(value * 100) / 100;
}

function getRequiredName(properties: CountryProperties, key: 'NAME' | 'NAME_ES' | 'NAME_PT') {
  const name = properties[key]?.trim();
  if (!name) throw new Error(`Missing ${key} for feature ${JSON.stringify(properties.NAME)}`);
  return name;
}

function getCountryLabel(properties: CountryProperties): CountryLabel {
  return {
    lat: getRounded(properties.LABEL_Y),
    lon: getRounded(properties.LABEL_X),
    rank: properties.LABELRANK,
    name: {
      en: getRequiredName(properties, 'NAME'),
      es: getRequiredName(properties, 'NAME_ES'),
      pt: getRequiredName(properties, 'NAME_PT'),
    },
  };
}

const { features } = JSON.parse(readFileSync(inputPath, 'utf8')) as {
  features: { properties: CountryProperties }[];
};

const labels = features
  .map(({ properties }) => properties)
  .filter((properties) => properties.LABELRANK <= MAX_LABEL_RANK)
  .sort(
    (a, b) =>
      a.LABELRANK - b.LABELRANK ||
      a.MIN_LABEL - b.MIN_LABEL ||
      getRequiredName(a, 'NAME').localeCompare(getRequiredName(b, 'NAME'), 'en'),
  )
  .map(getCountryLabel);

const entries = labels.map((label) => `  ${JSON.stringify(label)},\n`).join('');
writeFileSync(
  OUTPUT_PATH,
  `// Generated by scripts/build-globe-countries.ts from Natural Earth 1:50m admin 0 countries (public domain): ${SOURCE_URL}\n` +
    `export type CountryLabel = { lat: number; lon: number; rank: number; name: { en: string; es: string; pt: string } };\n` +
    `export const COUNTRY_LABELS: readonly CountryLabel[] = [\n${entries}];\n`,
);
console.log(`Wrote ${labels.length} country labels to ${OUTPUT_PATH}`);

import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

type Ring = [number, number][];
type Geometry =
  | { type: 'Polygon'; coordinates: Ring[] }
  | { type: 'MultiPolygon'; coordinates: Ring[][] };

const OUTPUT_PATH = path.resolve(import.meta.dirname, '../src/lib/globe/borders.data.ts');
const SOURCE_URL =
  'https://raw.githubusercontent.com/nvkelso/natural-earth-vector/v5.1.2/geojson/ne_110m_admin_0_countries.geojson';
const STEPS_PER_DEGREE = 100;
const ANTIMERIDIAN = 180 * STEPS_PER_DEGREE;
const SOUTH_POLE = -90 * STEPS_PER_DEGREE;

type Vertex = [number, number];
type Segment = [Vertex, Vertex];

function getRings(geometry: Geometry): Ring[] {
  return geometry.type === 'Polygon' ? geometry.coordinates : geometry.coordinates.flat();
}

function getQuantizedVertex([lon, lat]: [number, number]): Vertex {
  return [Math.round(lon * STEPS_PER_DEGREE), Math.round(lat * STEPS_PER_DEGREE)];
}

function getRingSegments(ring: Ring): Segment[] {
  const vertices = ring.map(getQuantizedVertex);
  return vertices.slice(1).map((vertex, index): Segment => [vertices[index], vertex]);
}

function isCutEdge([[lon1, lat1], [lon2, lat2]]: Segment): boolean {
  const alongAntimeridian = Math.abs(lon1) === ANTIMERIDIAN && Math.abs(lon2) === ANTIMERIDIAN;
  const alongSouthPole = lat1 === SOUTH_POLE && lat2 === SOUTH_POLE;
  return alongAntimeridian || alongSouthPole;
}

function isDegenerate([[lon1, lat1], [lon2, lat2]]: Segment): boolean {
  return lon1 === lon2 && lat1 === lat2;
}

function getVertexKey([lon, lat]: Vertex): string {
  return `${lon === -ANTIMERIDIAN ? ANTIMERIDIAN : lon},${lat}`;
}

function getSegmentKey([start, end]: Segment): string {
  return [getVertexKey(start), getVertexKey(end)].sort().join(';');
}

function getInt16Base64(values: number[]): string {
  const buffer = Buffer.alloc(values.length * 2);
  values.forEach((value, index) => buffer.writeInt16LE(value, index * 2));
  return buffer.toString('base64');
}

const inputPath = process.argv[2];
if (!inputPath)
  throw new Error(
    `Usage: node scripts/build-globe-borders.ts <ne_110m_admin_0_countries.geojson from ${SOURCE_URL}>`,
  );

const { features } = JSON.parse(readFileSync(inputPath, 'utf8')) as {
  features: { geometry: Geometry }[];
};
const segments = new Map<string, Segment>();
for (const segment of features
  .flatMap(({ geometry }) => getRings(geometry))
  .flatMap(getRingSegments)) {
  const key = getSegmentKey(segment);
  if (!isCutEdge(segment) && !isDegenerate(segment) && !segments.has(key))
    segments.set(key, segment);
}

writeFileSync(
  OUTPUT_PATH,
  `// Generated by scripts/build-globe-borders.ts from Natural Earth 1:110m admin 0 countries (public domain): ${SOURCE_URL}\n` +
    `export const BORDER_STEPS_PER_DEGREE = ${STEPS_PER_DEGREE};\n` +
    `export const BORDER_SEGMENT_COUNT = ${segments.size};\n` +
    `export const BORDER_SEGMENTS_BASE64 =\n  '${getInt16Base64([...segments.values()].flat(2))}';\n`,
);
console.log(`Wrote ${segments.size} segments to ${OUTPUT_PATH}`);

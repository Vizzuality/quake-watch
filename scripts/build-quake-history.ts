import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const OUTPUT_PATH = path.resolve(import.meta.dirname, '../src/server/og/quake-history.ts');
const SOURCE_URL =
  'https://earthquake.usgs.gov/fdsnws/event/1/query?format=csv&starttime=2000-01-01&endtime=2026-01-01&minmagnitude=6&eventtype=earthquake&orderby=magnitude-asc';

function getRounded(value: number): number {
  return Math.round(value * 10) / 10;
}

const inputPath = process.argv[2];
if (!inputPath)
  throw new Error(`Usage: node scripts/build-quake-history.ts <CSV from ${SOURCE_URL}>`);

const [header, ...rows] = readFileSync(inputPath, 'utf8').trim().split('\n');
const columns = header.split(',');
const [latitudeIndex, longitudeIndex, magnitudeIndex] = ['latitude', 'longitude', 'mag'].map(
  (name) => columns.indexOf(name),
);

const points = rows
  .map((row) => row.split(','))
  .map((cells) => [
    getRounded(Number(cells[longitudeIndex])),
    getRounded(Number(cells[latitudeIndex])),
    getRounded(Number(cells[magnitudeIndex])),
  ])
  .sort((a, b) => a[2] - b[2]);

writeFileSync(
  OUTPUT_PATH,
  `// Generated by scripts/build-quake-history.ts from the USGS catalogue (public domain): ${SOURCE_URL}\n` +
    `// "longitude latitude magnitude" triples separated by commas, smallest magnitude first.\n` +
    `export const QUAKE_HISTORY =\n  '${points.map((point) => point.join(' ')).join(',')}';\n`,
);
console.log(`Wrote ${points.length} earthquakes to ${OUTPUT_PATH}`);

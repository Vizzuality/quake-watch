import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

type Ring = [number, number][];
type Geometry =
  | { type: 'Polygon'; coordinates: Ring[] }
  | { type: 'MultiPolygon'; coordinates: Ring[][] };

const OUTPUT_PATH = path.resolve(import.meta.dirname, '../src/server/og/land-path.ts');
const SOURCE_URL =
  'https://raw.githubusercontent.com/nvkelso/natural-earth-vector/v5.1.2/geojson/ne_110m_land.geojson';

function getPoint([longitude, latitude]: [number, number]): string {
  return `${Math.round((longitude + 180) * 10) / 10} ${Math.round((90 - latitude) * 10) / 10}`;
}

function getRingPath(ring: Ring): string {
  const points = ring.map(getPoint).filter((point, index, all) => point !== all[index - 1]);
  return `M${points.join('L')}Z`;
}

function getPolygons(geometry: Geometry): Ring[][] {
  return geometry.type === 'Polygon' ? [geometry.coordinates] : geometry.coordinates;
}

const inputPath = process.argv[2];
if (!inputPath)
  throw new Error(
    `Usage: node scripts/build-land-path.ts <ne_110m_land.geojson from ${SOURCE_URL}>`,
  );

const { features } = JSON.parse(readFileSync(inputPath, 'utf8')) as {
  features: { geometry: Geometry }[];
};
const landPath = features
  .flatMap(({ geometry }) => getPolygons(geometry))
  .flatMap((rings) => rings.map(getRingPath))
  .join('');

writeFileSync(
  OUTPUT_PATH,
  `// Generated by scripts/build-land-path.ts from Natural Earth 1:110m land (public domain): ${SOURCE_URL}\n` +
    `export const LAND_PATH =\n  '${landPath}';\n`,
);
console.log(`Wrote ${landPath.length} characters to ${OUTPUT_PATH}`);
